suppressPackageStartupMessages(library(mixOmics))
set.seed(1)
X <- matrix(rnorm(200), 20, 10); colnames(X) <- paste0("g", 1:10)
y <- factor(rep(c("a", "b"), 10))
fit <- plsda(X, y, ncomp = 2)
pr <- predict(fit, newdata = X[1:5, , drop = FALSE])
cat("class(names(pr$class)):", paste(names(pr$class), collapse = ", "), "\n")
print(pr$class$max.dist)
cat("predict df cols:", paste(colnames(pr$predict), collapse = ", "), "\n")
print(pr$predict[1:5, , ])  # 3-D array (rows x classes x dims)
cat("variates scale check:\n")
cat("train sd:", apply(fit$variates$X, 2, sd), "\n")
cat("new sd:", apply(pr$variates, 2, sd), "\n")
