# 07c_fish_tplsda_loo.R : subject-grouped LOSO for the fish tPLS-DA (fills the comparison table)
suppressPackageStartupMessages({library(data.table); library(tensorOmics)})
source(file.path(Sys.getenv("TER_ROOT", getwd()), "code", "pipeline", "lib_tensor_helpers.R"))
base_dir <- Sys.getenv("TER_ROOT", getwd())
dat_dir <- file.path(base_dir, "data/GSE150318")
tab_dir <- file.path(base_dir, "results/tables")
X <- fread(file.path(dat_dir, "fish_X1000_long.csv"))
meta <- fread(file.path(dat_dir, "fish_meta.csv"))
genes <- setdiff(names(X), c("subj", "time"))
Xmat <- as.matrix(X[, ..genes]); rownames(Xmat) <- paste0("s", X$subj, "_t", X$time)
n <- nrow(meta)
X_tensor <- array(NA_real_, dim = c(n, length(genes), 2), dimnames = list(paste0("s", meta$subj), genes, c("10w", "20w")))
for (i in 1:n) for (k in 1:2) X_tensor[i, , k] <- Xmat[paste0("s", meta$subj[i], "_t", c(10, 20)[k]), ]
grp <- factor(meta$long_lived, levels = c(0, 1), labels = c("short_lived", "long_lived"))
dct <- make_dct(2)
pred <- tplsda_loo_predict(X_tensor, grp, dct, ncomp = 2)
ba <- balanced_acc(pred, grp)
cat("fish tPLS-DA subject-grouped LOSO balanced accuracy:", round(ba, 4), "\n")
source(file.path(Sys.getenv("TER_ROOT", getwd()), "code", "pipeline", "lib_p2a_helpers.R"))
loso_path <- file.path(tab_dir, "fish_loso_naive_vs_grouped.csv")
tab <- fread(loso_path)
new_row <- data.frame(analysis = "tPLS-DA, subject-grouped LOSO",
                      balanced_accuracy = ba, n_predictions = n)
tab <- upsert_rows(tab, new_row, keys = "analysis")
atomic_write_csv(tab, loso_path)
print(tab)
cat("DONE\n")
